/**
 * One-time Kibble data importer: SQLite petfood.db -> Supabase PostgreSQL.
 * Run locally with DATABASE_URL set in your terminal environment.
 * It creates missing tables and refuses to insert into non-empty target tables.
 */
require('dotenv').config();
const sqlite3 = require('sqlite3').verbose();
const { Client } = require('pg');
const path = require('path');

const sqlitePath = process.env.SQLITE_PATH || path.join(__dirname, 'petfood.db');
const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error('Missing DATABASE_URL. Set it in your local terminal environment before running.');
  process.exit(1);
}

const source = new sqlite3.Database(sqlitePath, sqlite3.OPEN_READONLY);
const target = new Client({ connectionString, ssl: { rejectUnauthorized: false } });
const q = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const all = (sql, params = []) => new Promise((resolve, reject) => source.all(sql, params, (e, rows) => e ? reject(e) : resolve(rows)));
const run = (sql, params = []) => new Promise((resolve, reject) => source.run(sql, params, function (e) { e ? reject(e) : resolve(this); }));

function pgType(col) {
  const t = String(col.type || '').toUpperCase();
  if (col.pk && t.includes('INT')) return 'BIGSERIAL';
  if (t.includes('INT')) return 'BIGINT';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'DOUBLE PRECISION';
  if (t.includes('BOOL')) return 'BOOLEAN';
  if (t.includes('BLOB')) return 'BYTEA';
  if (t.includes('DATE') || t.includes('TIME')) return 'TIMESTAMP';
  return 'TEXT';
}

async function main() {
  await target.connect();
  const tables = await all("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name");
  await target.query('BEGIN');
  try {
    for (const { name } of tables) {
      const cols = await all(`PRAGMA table_info(${q(name)})`);
      const ddlRows = await all(`SELECT sql FROM sqlite_master WHERE type='table' AND name=?`, [name]);
      const hasAutoincrement = /AUTOINCREMENT/i.test(ddlRows[0]?.sql || '');
      const createCols = cols.map(c => {
        let type = pgType(c);
        const integerPrimaryKey = c.pk && cols.filter(x => x.pk).length === 1 && String(c.type).toUpperCase().includes('INT');
        if (integerPrimaryKey) type = 'BIGINT';
        let part = `${q(c.name)} ${type}`;
        if (integerPrimaryKey && hasAutoincrement) {
          part += ' GENERATED BY DEFAULT AS IDENTITY';
        }
        if (c.notnull) part += ' NOT NULL';
        if (c.dflt_value !== null && c.dflt_value !== undefined) {
          const d = String(c.dflt_value);
          if (/^CURRENT_TIMESTAMP$/i.test(d)) part += ' DEFAULT CURRENT_TIMESTAMP';
          else if (/^-?\d+(\.\d+)?$/.test(d)) part += ` DEFAULT ${d}`;
          else if (/^NULL$/i.test(d)) {} // omit NULL default
          else if (/^'.*'$/.test(d)) part += ` DEFAULT ${d}`;
        }
        return part;
      });
      const pk = cols.filter(c => c.pk).sort((a,b) => a.pk-b.pk).map(c => q(c.name));
      if (pk.length) createCols.push(`PRIMARY KEY (${pk.join(', ')})`);

      // Preserve SQLite UNIQUE constraints, such as users.email and ingredients.name.
      // The application relies on these when it seeds rows with INSERT OR IGNORE.
      const indexes = await all(`PRAGMA index_list(${q(name)})`);
      for (const idx of indexes.filter(i => i.unique && !i.partial && i.origin === 'u')) {
        const idxCols = await all(`PRAGMA index_info(${q(idx.name)})`);
        const uniqueCols = idxCols.sort((a, b) => a.seqno - b.seqno).map(c => q(c.name));
        if (uniqueCols.length) createCols.push(`UNIQUE (${uniqueCols.join(', ')})`);
      }
      await target.query(`CREATE TABLE IF NOT EXISTS ${q(name)} (${createCols.join(', ')})`);

      const count = await target.query(`SELECT COUNT(*)::bigint AS n FROM ${q(name)}`);
      if (Number(count.rows[0].n) > 0) throw new Error(`Target table ${name} is not empty; stopped to avoid duplicates. Clear it only if you intend to replace its data.`);

      const rows = await all(`SELECT * FROM ${q(name)}`);
      if (!rows.length) { console.log(`${name}: 0 rows`); continue; }
      const names = cols.map(c => c.name);
      const insertSql = `INSERT INTO ${q(name)} (${names.map(q).join(', ')}) VALUES (${names.map((_, i) => `$${i+1}`).join(', ')})`;
      for (const row of rows) {
        const values = names.map(n => row[n] === undefined ? null : row[n]);
        await target.query(insertSql, values);
      }
      console.log(`${name}: imported ${rows.length} rows`);
    }
    // Reset generated integer primary-key sequences to the largest imported ID.
    for (const { name } of tables) {
      const cols = await all(`PRAGMA table_info(${q(name)})`);
      for (const c of cols.filter(c => c.pk && String(c.type).toUpperCase().includes('INT'))) {
        const seq = await target.query("SELECT pg_get_serial_sequence($1, $2) AS seq", [name, c.name]);
        if (seq.rows[0].seq) {
          await target.query(`SELECT setval($1::regclass, GREATEST(COALESCE((SELECT MAX(${q(c.name)}) FROM ${q(name)}), 1), 1), EXISTS (SELECT 1 FROM ${q(name)}))`, [seq.rows[0].seq]);
        }
      }
    }
    await target.query('COMMIT');
    console.log('Import completed. Verify row counts in Supabase before switching the live app.');
  } catch (err) {
    await target.query('ROLLBACK');
    throw err;
  } finally {
    await target.end();
    source.close();
  }
}
main().catch(e => { console.error('Import failed:', e.message); process.exitCode = 1; });
